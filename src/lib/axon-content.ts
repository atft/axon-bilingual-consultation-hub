export type ContactFields = {
  name: string;
  company: string;
  email: string;
  phone: string;
  service: string;
  message: string;
};
export function validateContact(fields: ContactFields) {
  const errors: Partial<Record<keyof ContactFields, "required" | "invalidEmail" | "invalidPhone">> =
    {};
  for (const key of ["name", "company", "email", "service", "message"] as const)
    if (!fields[key].trim()) errors[key] = "required";
  if (fields.email && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(fields.email))
    errors.email = "invalidEmail";
  if (fields.phone && !/^\+?[\d\s()-]{7,20}$/.test(fields.phone)) errors.phone = "invalidPhone";
  return errors;
}
